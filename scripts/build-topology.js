// Generates public/js/face-topology.js from MediaPipe's canonical face mesh.
// The 468-point mesh has holes for the eyes and mouth; we fill them with a
// triangle fan around an extra centre vertex so the textured face is solid.
// Run: bun run build:topology
import path from 'node:path';
import { FaceLandmarker as FL } from '@mediapipe/tasks-vision';

const T = FL.FACE_LANDMARKS_TESSELATION;
const tris = [];
for (let i = 0; i < T.length; i += 3) tris.push([T[i].start, T[i + 1].start, T[i + 2].start]);

const BASE = 478; // 468 mesh points + 10 iris points
const key = (a, b) => (a < b ? `${a}_${b}` : `${b}_${a}`);

// Directed edges, to keep the fan winding consistent with the mesh.
const directed = new Set();
const count = new Map();
for (const t of tris) {
  for (let k = 0; k < 3; k++) {
    const a = t[k], b = t[(k + 1) % 3];
    directed.add(`${a}>${b}`);
    count.set(key(a, b), (count.get(key(a, b)) || 0) + 1);
  }
}

// Boundary loops (edges used by exactly one triangle).
const adj = new Map();
for (const [k, c] of count) {
  if (c !== 1) continue;
  const [a, b] = k.split('_').map(Number);
  if (!adj.has(a)) adj.set(a, []);
  if (!adj.has(b)) adj.set(b, []);
  adj.get(a).push(b);
  adj.get(b).push(a);
}
const seen = new Set();
const loops = [];
for (const s of adj.keys()) {
  if (seen.has(s)) continue;
  const loop = [];
  let cur = s, prev = -1;
  while (cur !== undefined && !seen.has(cur)) {
    seen.add(cur);
    loop.push(cur);
    const next = adj.get(cur).find((x) => x !== prev && !seen.has(x));
    prev = cur;
    cur = next;
  }
  loops.push(loop);
}
loops.sort((a, b) => b.length - a.length);
const [outer, ...holes] = loops; // the face oval is the longest loop

const setOf = (conns) => new Set(conns.flatMap((c) => [c.start, c.end]));
const leftEye = setOf(FL.FACE_LANDMARKS_LEFT_EYE);
const rightEye = setOf(FL.FACE_LANDMARKS_RIGHT_EYE);
const leftIris = setOf(FL.FACE_LANDMARKS_LEFT_IRIS);
const rightIris = setOf(FL.FACE_LANDMARKS_RIGHT_IRIS);
// Iris centre is the one iris index that is not on the iris ring connections... the
// ring is 4 points; the centre is the remaining index of the 5-point block.
const irisCentre = (ring) => {
  const min = Math.min(...ring);
  return min - 1; // 468..472 → centre 468; 473..477 → centre 473
};

const holeDefs = holes.map((loop, i) => {
  const centre = BASE + i;
  let iris = null;
  if (loop.every((v) => leftEye.has(v))) iris = irisCentre([...leftIris]);
  else if (loop.every((v) => rightEye.has(v))) iris = irisCentre([...rightIris]);
  return { centre, iris, loop };
});

const fill = [];
for (const h of holeDefs) {
  const L = h.loop;
  for (let i = 0; i < L.length; i++) {
    const a = L[i], b = L[(i + 1) % L.length];
    // Existing triangle owns a>b → we must use b>a, and vice versa.
    if (directed.has(`${a}>${b}`)) fill.push([b, a, h.centre]);
    else fill.push([a, b, h.centre]);
  }
}

const allTris = tris.concat(fill);
const VERTS = BASE + holeDefs.length;

// Hop distance from the outer boundary, used to feather the edge of the face.
const nbr = Array.from({ length: VERTS }, () => new Set());
for (const t of allTris) for (let k = 0; k < 3; k++) {
  nbr[t[k]].add(t[(k + 1) % 3]);
  nbr[t[(k + 1) % 3]].add(t[k]);
}
const hops = new Array(VERTS).fill(255);
let frontier = [...outer];
for (const v of frontier) hops[v] = 0;
for (let d = 1; frontier.length; d++) {
  const next = [];
  for (const v of frontier) for (const n of nbr[v]) if (hops[n] === 255) { hops[n] = d; next.push(n); }
  frontier = next;
}

// Unique wireframe edges of the original mesh (no hole fills).
const lines = [];
const lineSeen = new Set();
for (const t of tris) for (let k = 0; k < 3; k++) {
  const a = t[k], b = t[(k + 1) % 3], kk = key(a, b);
  if (!lineSeen.has(kk)) { lineSeen.add(kk); lines.push(a, b); }
}

const out = `// AUTO-GENERATED by scripts/build-topology.js from @mediapipe/tasks-vision.
// Canonical MediaPipe face-mesh topology with eye and mouth holes filled.
export const BASE_VERTS = ${BASE};
export const VERT_COUNT = ${VERTS};
export const HOLES = ${JSON.stringify(holeDefs)};
export const TRIANGLES = new Uint16Array(${JSON.stringify(allTris.flat())});
export const LINES = new Uint16Array(${JSON.stringify(lines)});
export const EDGE_HOPS = new Uint8Array(${JSON.stringify(hops.map((h) => Math.min(h, 255)))});
export const FACE_OVAL = ${JSON.stringify(outer)};
`;
const dest = path.join(import.meta.dir, '..', 'public', 'js', 'face-topology.js');
await Bun.write(dest, out);
console.log(`wrote ${dest}: ${allTris.length} triangles, ${lines.length / 2} lines, ${holeDefs.length} holes filled`);
console.log(holeDefs.map((h) => `hole ${h.centre}: ${h.loop.length} verts, iris ${h.iris}`).join('\n'));
